def tree_digest(fd: int, prefix: str) -> str:
    digest = hashlib.sha256()
    before = identity(os.fstat(fd))
    for child in sorted(os.listdir(fd)):
        if child.startswith(".") or NAME.fullmatch(child) is None:
            deny("unsafe-manifest-tree-name")
        cfd = os.open(child, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=fd)
        try:
            meta = os.fstat(cfd)
            path = prefix + "/" + child
            if stat.S_ISDIR(meta.st_mode):
                digest.update(bytes.fromhex(tree_digest(cfd, path)))
            elif stat.S_ISREG(meta.st_mode) and meta.st_nlink == 1 and not meta.st_mode & 0o022:
                payload = read_fd(cfd, 256 * 1024 * 1024)
                digest.update((path + "|" + str(meta.st_size) + "|" + sha256(payload) + "\n").encode("utf-8"))
            else:
                deny("unsafe-manifest-tree-node")
        finally:
            os.close(cfd)
    if identity(os.fstat(fd)) != before:
        deny("drift-manifest-tree")
    # The source manifest's tree scheme is the hash of its complete textual
    # member record stream, not a recursive composition of child digests.
    # Recompute that stream directly so this function cannot silently accept
    # a different tree representation.
    stream = hashlib.sha256()
    def visit(directory_fd: int, name: str) -> None:
        start = identity(os.fstat(directory_fd))
        for leaf in sorted(os.listdir(directory_fd)):
            if leaf.startswith(".") or NAME.fullmatch(leaf) is None:
                deny("unsafe-manifest-tree-name")
            leaf_fd = os.open(leaf, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=directory_fd)
            try:
                leaf_meta = os.fstat(leaf_fd)
                leaf_path = name + "/" + leaf
                if stat.S_ISDIR(leaf_meta.st_mode):
                    visit(leaf_fd, leaf_path)
                elif stat.S_ISREG(leaf_meta.st_mode) and leaf_meta.st_nlink == 1 and not leaf_meta.st_mode & 0o022:
                    payload = read_fd(leaf_fd, 256 * 1024 * 1024)
                    stream.update((leaf_path + "|" + str(leaf_meta.st_size) + "|" + sha256(payload) + "\n").encode("utf-8"))
                else:
                    deny("unsafe-manifest-tree-node")
            finally:
                os.close(leaf_fd)
        if identity(os.fstat(directory_fd)) != start:
            deny("drift-manifest-tree")
    visit(fd, prefix)
    return stream.hexdigest()


def verify_manifest(source: Path) -> tuple[dict[str, object], str]:
    manifest_path = source / "script/source_snapshot_manifest.jsonl"
    raw = descriptor(manifest_path, maximum=1024 * 1024)
    fd = os.open(manifest_path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
    root_fd = os.open(source, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
    try:
        payload = read_fd(fd, 1024 * 1024)
        lines = payload.decode("utf-8", "strict").splitlines()
        rows = [json.loads(line) for line in lines]
        if not rows or any(canonical(row).rstrip(b"\n").decode("utf-8") != line for row, line in zip(rows, lines)):
            deny("noncanonical-source-manifest")
        paths = [row.get("path") for row in rows]
        if paths != sorted(paths) or len(paths) != len(set(paths)):
            deny("unsafe-source-manifest-inventory")
        for row in rows:
            if set(row) - {"schema", "type", "path", "mode", "size", "sha256"} or row.get("schema") != "lidswitch-source-manifest-v1":
                deny("unsafe-source-manifest-row")
            relative = row.get("path")
            if not isinstance(relative, str) or relative.startswith("/") or ".." in relative.split("/"):
                deny("unsafe-source-manifest-path")
            entry_fd = os.open(relative, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=root_fd)
            try:
                info = os.fstat(entry_fd)
                if row.get("type") == "file":
                    payload_entry = read_fd(entry_fd, 256 * 1024 * 1024)
                    if (not stat.S_ISREG(info.st_mode) or info.st_size != row.get("size") or
                            stat.S_IMODE(info.st_mode) != row.get("mode") or sha256(payload_entry) != row.get("sha256")):
                        deny("source-manifest-file-mismatch: " + relative)
                elif row.get("type") == "tree":
                    if not stat.S_ISDIR(info.st_mode) or tree_digest(entry_fd, relative) != row.get("sha256"):
                        deny("source-manifest-tree-mismatch: " + relative)
                else:
                    deny("unsafe-source-manifest-row")
            finally:
                os.close(entry_fd)
        return raw, sha256(payload)
    finally:
        os.close(root_fd)
        os.close(fd)



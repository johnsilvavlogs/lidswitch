def deny(reason: str) -> None:
    raise Denied(reason)


def canonical(value: object) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8") + b"\n"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_fd(fd: int, limit: int = LIMIT, *, single_link: bool = True) -> bytes:
    before = os.fstat(fd)
    if not stat.S_ISREG(before.st_mode) or (single_link and before.st_nlink != 1) or before.st_nlink < 1 or not 0 < before.st_size <= limit:
        deny("unsafe-regular-descriptor")
    os.lseek(fd, 0, os.SEEK_SET)
    data = bytearray()
    while len(data) < before.st_size:
        try:
            piece = os.read(fd, min(131072, before.st_size - len(data)))
        except InterruptedError:
            continue
        if not piece:
            deny("short-regular-descriptor")
        data.extend(piece)
    if os.read(fd, 1) or identity(os.fstat(fd)) != identity(before):
        deny("drift-regular-descriptor")
    return bytes(data)


def identity(info: os.stat_result) -> tuple[int, int, int, int, int, int, int]:
    return (info.st_dev, info.st_ino, info.st_uid, info.st_gid, stat.S_IMODE(info.st_mode), info.st_nlink, info.st_size)


def descriptor(path: Path, *, system: bool = False, maximum: int = LIMIT) -> dict[str, object]:
    if path.is_symlink():
        deny("symlinked-descriptor: " + str(path))
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
    try:
        before = os.fstat(fd)
        if not stat.S_ISREG(before.st_mode) or (not system and before.st_nlink != 1) or before.st_nlink < 1 or before.st_size <= 0:
            deny("unsafe-descriptor: " + str(path))
        if before.st_mode & 0o022:
            deny("writable-descriptor: " + str(path))
        if system and (before.st_uid != 0 or before.st_gid != 0):
            deny("unowned-system-descriptor: " + str(path))
        data = read_fd(fd, maximum, single_link=not system)
        after = os.fstat(fd)
        if identity(before) != identity(after):
            deny("drift-descriptor: " + str(path))
        return {"path": str(path), "dev": before.st_dev, "inode": before.st_ino,
                "uid": before.st_uid, "gid": before.st_gid, "mode": stat.S_IMODE(before.st_mode),
                "nlink": before.st_nlink, "size": before.st_size, "sha256": sha256(data)}
    finally:
        os.close(fd)


def checked_directory(path: Path) -> dict[str, int]:
    if path.is_symlink():
        deny("symlinked-directory: " + str(path))
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
    try:
        info = os.fstat(fd)
        if not stat.S_ISDIR(info.st_mode) or info.st_nlink < 2 or info.st_mode & 0o022:
            deny("unsafe-directory: " + str(path))
        return {"dev": info.st_dev, "inode": info.st_ino, "uid": info.st_uid, "gid": info.st_gid,
                "mode": stat.S_IMODE(info.st_mode), "nlink": info.st_nlink}
    finally:
        os.close(fd)


def checked_system_directory_selector(path: Path) -> dict[str, object]:
    parent = path.parent
    parent_before = checked_directory(parent)
    if parent_before["uid"] != 0 or parent_before["gid"] != 0:
        deny("unowned-system-directory: " + str(parent))

    selector_before = os.lstat(path)
    if not stat.S_ISLNK(selector_before.st_mode):
        deny("non-symlinked-system-selector: " + str(path))
    if selector_before.st_uid != 0 or selector_before.st_gid != 0 or selector_before.st_nlink != 1:
        deny("unsafe-system-selector: " + str(path))
    target_name = os.readlink(path)
    target_component = Path(target_name)
    if (not target_name or target_component.is_absolute() or len(target_component.parts) != 1
            or target_name in {".", ".."}):
        deny("unsafe-system-selector-target: " + str(path))

    target_path = parent / target_name
    target = checked_directory(target_path)
    if target["uid"] != 0 or target["gid"] != 0:
        deny("unowned-system-directory: " + str(target_path))
    selector_after = os.lstat(path)
    parent_after = checked_directory(parent)
    if identity(selector_before) != identity(selector_after) or os.readlink(path) != target_name:
        deny("drift-system-selector: " + str(path))
    if parent_before != parent_after:
        deny("drift-system-directory: " + str(parent))
    return {
        "selector": {"path": str(path), "dev": selector_before.st_dev, "inode": selector_before.st_ino,
                     "uid": selector_before.st_uid, "gid": selector_before.st_gid,
                     "mode": stat.S_IMODE(selector_before.st_mode), "nlink": selector_before.st_nlink,
                     "size": selector_before.st_size, "target": target_name, "type": "symlink"},
        "parent": {"path": str(parent), **parent_before},
        "target": {"path": str(target_path), **target},
    }


